-- Control plane Slice 0 (F1, F1n): every artifact publication a session makes, and the
-- bursts that announce them. Publications are keyed by their log occurrence; a burst id is
-- minted once from its seed publication and never recomputed (model/bursts.md).
CREATE TABLE IF NOT EXISTS forge_artifact_publications (
    publication_id UUID PRIMARY KEY,
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    host TEXT NOT NULL,
    session_id UUID NOT NULL,
    session_seq BIGINT NOT NULL,
    ordinal INTEGER NOT NULL DEFAULT 0,
    source TEXT NOT NULL,
    provider TEXT NOT NULL,
    provider_key TEXT NOT NULL,
    provider_version TEXT,
    provider_seq INTEGER,
    revision_id TEXT NOT NULL,
    title TEXT,
    url TEXT,
    at TIMESTAMPTZ NOT NULL,
    origin TEXT NOT NULL CHECK (origin IN ('live', 'backfill')),
    tool_use_id TEXT,
    artifact_type TEXT NOT NULL,
    type_url TEXT,
    mime TEXT,
    subagent BOOLEAN NOT NULL DEFAULT FALSE,
    version_label TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (host, session_id, session_seq, ordinal)
);
CREATE INDEX IF NOT EXISTS idx_forge_artifact_publications_key
    ON forge_artifact_publications (provider, provider_key, at);
CREATE INDEX IF NOT EXISTS idx_forge_artifact_publications_session
    ON forge_artifact_publications (session_id, session_seq);

CREATE SEQUENCE IF NOT EXISTS forge_artifact_bursts_rev_seq;
CREATE TABLE IF NOT EXISTS forge_artifact_bursts (
    burst_id UUID PRIMARY KEY,
    rev BIGINT NOT NULL DEFAULT nextval('forge_artifact_bursts_rev_seq'),
    host TEXT NOT NULL,
    provider_key TEXT NOT NULL,
    origin TEXT NOT NULL CHECK (origin IN ('live', 'backfill')),
    started_at TIMESTAMPTZ NOT NULL,
    last_at TIMESTAMPTZ NOT NULL,
    publications INTEGER NOT NULL,
    seed_session_id UUID NOT NULL,
    seed_session_seq BIGINT NOT NULL,
    due_at TIMESTAMPTZ,
    notification_id UUID,
    suppressed_by UUID,
    suppress_reason TEXT,
    emitted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_forge_artifact_bursts_key
    ON forge_artifact_bursts (host, provider_key, origin, last_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_forge_artifact_bursts_rev
    ON forge_artifact_bursts (rev);
-- The durable hold: open live bursts, by when they are due.
CREATE INDEX IF NOT EXISTS idx_forge_artifact_bursts_due
    ON forge_artifact_bursts (due_at)
    WHERE due_at IS NOT NULL AND notification_id IS NULL
      AND suppressed_by IS NULL AND suppress_reason IS NULL;

CREATE TABLE IF NOT EXISTS forge_artifact_burst_publications (
    burst_id UUID NOT NULL REFERENCES forge_artifact_bursts(burst_id) ON DELETE CASCADE,
    publication_id UUID NOT NULL UNIQUE
        REFERENCES forge_artifact_publications(publication_id) ON DELETE CASCADE,
    bridged UUID[] NOT NULL DEFAULT '{}',
    PRIMARY KEY (burst_id, publication_id)
);

-- The suppression recheck looks for agent notices created inside a burst's window.
CREATE INDEX IF NOT EXISTS idx_forge_notifications_agent_created
    ON forge_notifications (created_at)
    WHERE source = 'agent';
