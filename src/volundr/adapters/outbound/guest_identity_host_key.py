"""Guest identity from a signature made with the guest's pinned SSH host key.

The VM's Ed25519 host key is generated by Forge before the machine exists, stored in
the allocation's machine bootstrap and written into the guest. The guest agent signs
each metadata request with it; Forge verifies against the public key it holds for that
allocation. The key never leaves the guest and Forge keeps it only in the bootstrap.

Signed bytes are ``niuu.adapters.node_signature.signing_message`` (the scheme of
``niuu join`` node requests): method, path, a millisecond timestamp and the body hash.
Replay is bounded the same way: the timestamp must strictly increase per allocation,
advanced by one atomic conditional write, inside a clock-skew window. Every rejection is
the same ``GuestAuthenticationError`` so a caller cannot probe which allocations exist.
"""

from __future__ import annotations

import base64
import binascii
import logging
import math
import time
from collections.abc import Awaitable, Callable, Mapping
from typing import Protocol
from uuid import UUID

from cryptography.exceptions import InvalidSignature, UnsupportedAlgorithm
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
from cryptography.hazmat.primitives.serialization import load_ssh_public_key

from niuu.adapters.node_signature import signing_message
from volundr.adapters.outbound.ssh_guest_access import HOST_KEY_PATH
from volundr.domain.compute import Machine, MachineBootstrap
from volundr.domain.guest_credentials import GuestAuthenticationError, GuestIdentity, GuestRequest

logger = logging.getLogger(__name__)

ALLOCATION_HEADER = "Niuu-Guest-Allocation"
TIMESTAMP_HEADER = "Niuu-Guest-Timestamp"
SIGNATURE_HEADER = "Niuu-Guest-Signature"

#: An Ed25519 signature is always this long (RFC 8032); a different length cannot verify.
_ED25519_SIGNATURE_BYTES = 64


class GuestRequestWatermarks(Protocol):
    """Per-allocation replay watermark, advanced atomically."""

    async def try_advance(self, allocation_id: UUID, timestamp_ms: int) -> bool:
        """Store ``timestamp_ms`` iff it is greater than the stored one (or none exists)."""


MachineBootstrapFor = Callable[[UUID], Awaitable[MachineBootstrap | None]]
MachineFor = Callable[[UUID], Awaitable[Machine | None]]


class HostKeyGuestIdentity(GuestIdentity):
    """Authenticates a guest by an Ed25519 signature made with its pinned host key."""

    def __init__(
        self,
        *,
        machine_bootstrap_for: MachineBootstrapFor,
        watermarks: GuestRequestWatermarks,
        clock_skew_seconds: float = 30.0,
        key_source: str = "bootstrap",
        machine_for: MachineFor | None = None,
    ) -> None:
        if not math.isfinite(clock_skew_seconds) or clock_skew_seconds <= 0:
            raise ValueError("clock_skew_seconds must be a positive, finite number")
        if key_source not in {"bootstrap", "registered"}:
            raise ValueError("key_source must be 'bootstrap' or 'registered'")
        if key_source == "registered" and machine_for is None:
            raise ValueError("key_source 'registered' needs the machine_for port")
        self._machine_bootstrap_for = machine_bootstrap_for
        self._machine_for = machine_for
        self._key_source = key_source
        self._watermarks = watermarks
        self._clock_skew_ms = clock_skew_seconds * 1000

    @property
    def serves_slots(self) -> bool:
        # The host key lives in the machine bootstrap; nothing is registered or
        # retired per session.
        return True

    def agent_auth(self, allocation_id: UUID) -> dict:
        return {"kind": "host_key", "key_path": HOST_KEY_PATH}

    def agent_mounts(self) -> tuple[dict, ...]:
        return ({"source": HOST_KEY_PATH, "target": HOST_KEY_PATH, "readonly": True},)

    async def authenticate(self, request: GuestRequest) -> UUID:
        headers = {name.lower(): value for name, value in request.headers.items()}
        allocation_id, timestamp_ms, signature = self._parse(headers)

        public_key = await self._stored_key(allocation_id)
        message = signing_message(request.method, request.path, timestamp_ms, request.body)
        try:
            public_key.verify(signature, message)
        except InvalidSignature:
            raise GuestAuthenticationError from None

        if abs(time.time() * 1000 - timestamp_ms) > self._clock_skew_ms:
            raise GuestAuthenticationError
        # The watermark advance is the replay boundary: one conditional write, so two
        # concurrent requests with the same or an older timestamp cannot both pass.
        if not await self._watermarks.try_advance(allocation_id, timestamp_ms):
            raise GuestAuthenticationError
        return allocation_id

    @staticmethod
    def _parse(headers: Mapping[str, str]) -> tuple[UUID, int, bytes]:
        try:
            allocation_id = UUID(headers[ALLOCATION_HEADER.lower()])
            raw_timestamp = headers[TIMESTAMP_HEADER.lower()]
            if not raw_timestamp.isascii() or not raw_timestamp.isdigit():
                raise ValueError("timestamp must be unsigned decimal milliseconds")
            timestamp_ms = int(raw_timestamp)
            signature = base64.b64decode(headers[SIGNATURE_HEADER.lower()], validate=True)
        except (KeyError, ValueError, binascii.Error):
            raise GuestAuthenticationError from None
        if len(signature) != _ED25519_SIGNATURE_BYTES:
            raise GuestAuthenticationError
        return allocation_id, timestamp_ms, signature

    async def _stored_key(self, allocation_id: UUID) -> Ed25519PublicKey:
        """The allocation's public key: from the bootstrap Forge generated, or, for a
        registered host, the key the host registered at pairing (configured, never tried)."""
        if self._key_source == "registered":
            machine = await self._machine_for(allocation_id)
            if machine is None:
                raise GuestAuthenticationError
            if not machine.host_public_key:
                logger.error(
                    "Allocation %s is on a machine with no registered host key; its guest "
                    "cannot authenticate (is the provider a registered-host provider?)",
                    allocation_id,
                )
                raise GuestAuthenticationError
            return self._parse_key(allocation_id, machine.host_public_key, "registered host key")
        bootstrap = await self._machine_bootstrap_for(allocation_id)
        if bootstrap is None:
            raise GuestAuthenticationError
        return self._public_key(allocation_id, bootstrap)

    @classmethod
    def _public_key(cls, allocation_id: UUID, machine: MachineBootstrap) -> Ed25519PublicKey:
        path = HOST_KEY_PATH + ".pub"
        content = next((item.content for item in machine.files if item.path == path), None)
        if content is None:
            logger.error(
                "Allocation %s has no %s in its machine bootstrap; its guest cannot "
                "authenticate (is the compute pool's guest identity host_key?)",
                allocation_id,
                path,
            )
            raise GuestAuthenticationError
        return cls._parse_key(allocation_id, content, path)

    @staticmethod
    def _parse_key(allocation_id: UUID, content: str, path: str) -> Ed25519PublicKey:
        try:
            key = load_ssh_public_key(content.strip().encode())
        except (ValueError, binascii.Error, UnsupportedAlgorithm):
            key = None
        if not isinstance(key, Ed25519PublicKey):
            logger.error("Allocation %s holds a %s that is not an Ed25519 key", allocation_id, path)
            raise GuestAuthenticationError
        return key
